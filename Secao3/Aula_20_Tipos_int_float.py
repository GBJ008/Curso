#tipos int e float
# int -> Número inteiro
# o tipo int representa qualquer número  sendo:
print(11)# inteiro
print(-11)# inteiro negativo
print(0) # inteiro sem valor
#float -> Número com  ponto flutuante
# o tipo float representa qualquer número
#positivo ou negativo com ponto flutuante.
# Float sem sinal é considerado positivo.
print(1.1)# número flutuante positivo
print(-1.1)# número flutuante negativo
# A função type mostra o tipo que o Python
#inferior ao valor.
# calabou = executável
# A "Função/ class" type serve para saber qual a classificação( int,float,bool etc...)
print(type())